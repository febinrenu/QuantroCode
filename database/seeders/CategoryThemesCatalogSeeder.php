        $now = Carbon::now();
        $unitId = Unit::where('ShortName', 'pc')->value('id') ?: (Unit::first()?->id ?? 1);
        $setting = Setting::first();
        $warehouseId = $setting?->warehouse_id ?: (Warehouse::value('id') ?? 1);

        $categories = $this->seedCategories($now);
